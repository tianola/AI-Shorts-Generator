"""Synthesise the sub boom sound effects with ffmpeg lavfi.

Usage:
    python scripts/build_sfx.py [--force] [--dry-run]

Writes into <STORAGE_ROOT>/assets/sfx/sub_boom/:
    sub_boom_1.wav  about 1.4 s, sweep 70 Hz -> 35 Hz, peak -3 dBFS
    sub_boom_2.wav  about 1.1 s, sweep 90 Hz -> 40 Hz, peak -4 dBFS

Every sample is generated by ffmpeg's aevalsrc source: no downloads and no
third-party audio. Output is 48 kHz stereo 16-bit PCM. Existing files are kept
unless --force is given. Each file is rendered to a float intermediate, its
peak is measured with astats, and a single volume gain moves the peak to the
target before the 16-bit write.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

BACKEND_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BACKEND_DIR)

from config import settings  # noqa: E402

SAMPLE_RATE = 48000
FFMPEG_TIMEOUT = 120
FFPROBE_TIMEOUT = 60
LOWPASS_HZ = 120
ATTACK_RATE = 400   # 1-exp(-400 t): roughly a 2.5 ms attack
DECAY_RATE = 3.0    # exp(-3 t) body decay

# A linear chirp from f0 to f1 over T has instantaneous frequency
# f(t) = f0 - (f0 - f1) / T * t, so its phase is
# 2*pi*(f0*t - (f0 - f1) / (2 T) * t^2).
VARIANTS = [
    {"name": "sub_boom_1.wav", "duration": 1.4, "f0": 70.0, "f1": 35.0, "peak_db": -3.0},
    {"name": "sub_boom_2.wav", "duration": 1.1, "f0": 90.0, "f1": 40.0, "peak_db": -4.0},
]

PEAK_RE = re.compile(r"Peak level dB:\s*(-?[0-9.]+|-inf)")


def run_ffmpeg(args):
    cmd = ["ffmpeg", "-hide_banner", "-nostats", "-loglevel", "error", "-y", *args]
    proc = subprocess.run(
        cmd, capture_output=True, text=True, timeout=FFMPEG_TIMEOUT, check=False
    )
    if proc.returncode != 0:
        raise RuntimeError(f"ffmpeg failed ({proc.returncode}): {proc.stderr.strip()}")


def measure_peak_db(path):
    """Overall true peak in dBFS from astats. The last match is the Overall block."""
    proc = subprocess.run(
        ["ffmpeg", "-hide_banner", "-nostats", "-loglevel", "info",
         "-i", path, "-af", "astats", "-f", "null", "-"],
        capture_output=True, text=True, timeout=FFMPEG_TIMEOUT, check=False,
    )
    matches = PEAK_RE.findall(proc.stderr)
    if proc.returncode != 0 or not matches:
        raise RuntimeError(f"could not measure peak of {path}: {proc.stderr.strip()}")
    value = matches[-1]
    return float("-inf") if value == "-inf" else float(value)


def probe_duration(path):
    proc = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", path],
        capture_output=True, text=True, timeout=FFPROBE_TIMEOUT, check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"ffprobe failed for {path}: {proc.stderr.strip()}")
    return float(proc.stdout.strip())


def synthesise(variant, out_path):
    f0, f1, dur = variant["f0"], variant["f1"], variant["duration"]
    coeff = (f0 - f1) / (2.0 * dur)
    expr = (
        f"sin(2*PI*({f0}*t-{coeff:.6f}*t*t))"
        f"*(1-exp(-{ATTACK_RATE}*t))*exp(-{DECAY_RATE}*t)"
    )
    src = f"aevalsrc={expr}|{expr}:s={SAMPLE_RATE}:d={dur}:c=stereo"
    part_path = out_path + ".part.wav"

    with tempfile.TemporaryDirectory() as tmp:
        raw_path = os.path.join(tmp, "raw.wav")
        run_ffmpeg([
            "-f", "lavfi", "-i", src,
            "-af", f"lowpass=f={LOWPASS_HZ}",
            "-c:a", "pcm_f32le", "-ar", str(SAMPLE_RATE), "-ac", "2",
            raw_path,
        ])
        measured = measure_peak_db(raw_path)
        gain_db = variant["peak_db"] - measured
        run_ffmpeg([
            "-i", raw_path,
            "-af", f"volume={gain_db:.4f}dB",
            "-c:a", "pcm_s16le", "-ar", str(SAMPLE_RATE), "-ac", "2",
            part_path,
        ])

    os.replace(part_path, out_path)
    return measured, gain_db


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--force", action="store_true",
                        help="rebuild files that already exist")
    parser.add_argument("--dry-run", action="store_true",
                        help="print what would be written, write nothing")
    args = parser.parse_args()

    sfx_dir = os.path.join(settings.STORAGE_ROOT, "assets", "sfx", "sub_boom")
    print(f"STORAGE_ROOT: {settings.STORAGE_ROOT}")
    print(f"Target folder: {sfx_dir}")

    if not args.dry_run:
        os.makedirs(sfx_dir, exist_ok=True)

    for variant in VARIANTS:
        out_path = os.path.join(sfx_dir, variant["name"])
        exists = os.path.exists(out_path)

        if exists and not args.force:
            print(f"skip {out_path} (exists; use --force to rebuild)")
            continue
        if args.dry_run:
            verb = "would rebuild" if exists else "would write"
            print(f"{verb} {out_path}  ({variant['f0']:g} -> {variant['f1']:g} Hz, "
                  f"{variant['duration']} s, target peak {variant['peak_db']} dBFS)")
            continue

        measured, gain_db = synthesise(variant, out_path)
        duration = probe_duration(out_path)
        peak = measure_peak_db(out_path)
        print(f"wrote {out_path}")
        print(f"  raw peak before gain {measured:.2f} dBFS, gain {gain_db:+.2f} dB")
        print(f"  duration {duration:.3f} s  peak {peak:.2f} dBFS")

    return 0


if __name__ == "__main__":
    sys.exit(main())
