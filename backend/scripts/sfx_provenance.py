"""Write backend/assets/sfx/PROVENANCE.md, a provenance table for every audio file
under <STORAGE_ROOT>/assets/sfx (searched recursively).

Usage:
    python scripts/sfx_provenance.py

The script rewrites PROVENANCE.md from scratch on each run, so it is idempotent.
Files named sub_boom_* were made by scripts/build_sfx.py. Every other file has no
recorded origin and is marked UNVERIFIED.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

BACKEND_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BACKEND_DIR)

from config import settings  # noqa: E402

AUDIO_EXTENSIONS = {".wav", ".mp3", ".ogg", ".oga", ".flac", ".m4a", ".aac",
                    ".aif", ".aiff", ".opus"}
FFMPEG_TIMEOUT = 300
FFPROBE_TIMEOUT = 60
PEAK_RE = re.compile(r"Peak level dB:\s*(-?[0-9.]+|-inf)")

SYNTH_ORIGIN = "synthesised by backend/scripts/build_sfx.py (ffmpeg lavfi)"
SYNTH_LICENCE = "generated here, no third-party material"
UNKNOWN_ORIGIN = ("unknown: predates provenance tracking; round durations suggest "
                  "generated placeholders")
UNKNOWN_LICENCE = "UNVERIFIED"

HEADER = """# Sound effect provenance

Generated by `backend/scripts/sfx_provenance.py`. Do not edit by hand; rerun the script.

## Rules

- Only CC0 or self-generated assets may ship.
- Files marked UNVERIFIED must be replaced or verified before any distribution.
- New downloaded packs must be added to this table with their source URL, and their
  licence text checked before use. For example, the Wyzowl SFX kit is listed as CC0 on
  its page, but the repository LICENSE has not yet been checked.
"""


def sha256_of(path):
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def probe_duration_and_rate(path):
    proc = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "a:0",
         "-show_entries", "format=duration:stream=sample_rate",
         "-of", "json", path],
        capture_output=True, text=True, timeout=FFPROBE_TIMEOUT, check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"ffprobe failed for {path}: {proc.stderr.strip()}")
    info = json.loads(proc.stdout)
    duration = float(info["format"]["duration"])
    rate = int(info["streams"][0]["sample_rate"])
    return duration, rate


def peak_dbfs(path):
    proc = subprocess.run(
        ["ffmpeg", "-hide_banner", "-nostats", "-loglevel", "info",
         "-i", path, "-af", "astats", "-f", "null", "-"],
        capture_output=True, text=True, timeout=FFMPEG_TIMEOUT, check=False,
    )
    matches = PEAK_RE.findall(proc.stderr)
    if proc.returncode != 0 or not matches:
        raise RuntimeError(f"could not measure peak of {path}")
    value = matches[-1]
    return "-inf" if value == "-inf" else f"{float(value):.2f}"


def category_for(rel_path):
    parts = rel_path.split("/")
    if len(parts) > 1:
        return parts[0]
    stem = os.path.splitext(parts[0])[0]
    return re.sub(r"_\d+$", "", stem)


def origin_for(rel_path):
    parts = rel_path.split("/")
    basename = parts[-1]
    if parts[0] == "sub_boom" and basename.startswith("sub_boom_"):
        return SYNTH_ORIGIN, SYNTH_LICENCE
    return UNKNOWN_ORIGIN, UNKNOWN_LICENCE


def collect_files(root):
    found = []
    for dirpath, _dirnames, filenames in os.walk(root):
        for name in filenames:
            if os.path.splitext(name)[1].lower() in AUDIO_EXTENSIONS:
                full = os.path.join(dirpath, name)
                rel = os.path.relpath(full, root).replace(os.sep, "/")
                found.append((rel, full))
    found.sort(key=lambda item: item[0])
    return found


def main():
    sfx_root = os.path.join(settings.STORAGE_ROOT, "assets", "sfx")
    if not os.path.isdir(sfx_root):
        print(f"No sfx folder at {sfx_root}", file=sys.stderr)
        return 1

    files = collect_files(sfx_root)
    rows = []
    for rel, full in files:
        duration, rate = probe_duration_and_rate(full)
        peak = peak_dbfs(full)
        origin, licence = origin_for(rel)
        rows.append(
            f"| {rel} | {sha256_of(full)} | {duration:.3f} | {rate} | {peak} | "
            f"{category_for(rel)} | {origin} | {licence} |"
        )
        print(f"{rel}  {duration:.3f} s  {rate} Hz  peak {peak} dBFS  {licence}")

    table_header = (
        "| file | SHA-256 | duration (s) | sample rate (Hz) | peak (dBFS) | "
        "category | origin | licence |\n"
        "|---|---|---|---|---|---|---|---|"
    )
    body = HEADER + "\n## Files\n\n" + table_header + "\n" + "\n".join(rows) + "\n"

    out_dir = os.path.join(BACKEND_DIR, "assets", "sfx")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "PROVENANCE.md")
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)

    print(f"{len(rows)} files listed in {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
